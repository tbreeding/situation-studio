import { createHash } from "node:crypto";
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const snapshotRoot = path.join(
  repositoryRoot,
  "packages",
  "review-policy",
  "policy",
);
const versionPath = path.join(
  repositoryRoot,
  "packages",
  "review-policy",
  "src",
  "version.ts",
);
const requiredFiles = [
  "SKILL.md",
  "references/agent-contracts.md",
  "references/framework-lenses.md",
  "references/leadership-field-guide.md",
  "references/plain-global-english.md",
  "references/teaching-alignment.md",
];

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function optionValue(name) {
  const index = process.argv.indexOf(name);
  if (index < 0) return undefined;
  const value = process.argv[index + 1];
  if (!value || value.startsWith("--"))
    throw new Error(`${name} requires a path.`);
  return path.resolve(value);
}

async function exists(target) {
  try {
    await access(target);
    return true;
  } catch {
    return false;
  }
}

async function loadSnapshot(root) {
  const files = [];
  for (const relativePath of requiredFiles) {
    const body = await readFile(path.join(root, relativePath));
    files.push({
      path: relativePath,
      sha256: sha256(body),
      bytes: body.byteLength,
      body,
    });
  }
  const sourceHash = sha256(
    files
      .map((file) => `${file.path}\0${file.sha256}\0${file.bytes}\n`)
      .join(""),
  );
  return {
    schemaVersion: "review-policy-snapshot-v1",
    policyName: "review-leadership-situations",
    version: `review-leadership-situations-${sourceHash.slice(0, 16)}`,
    sourceHash,
    files,
  };
}

function manifestFor(snapshot) {
  return {
    schemaVersion: snapshot.schemaVersion,
    policyName: snapshot.policyName,
    version: snapshot.version,
    sourceHash: snapshot.sourceHash,
    files: snapshot.files.map(({ path: filePath, sha256: hash, bytes }) => ({
      path: filePath,
      sha256: hash,
      bytes,
    })),
  };
}

function versionModule(snapshot) {
  return [
    "// Generated by scripts/sync-review-policy.mjs. Do not edit by hand.",
    "export const REVIEW_POLICY_VERSION =",
    `  ${JSON.stringify(snapshot.version)};`,
    "export const REVIEW_POLICY_SOURCE_HASH =",
    `  ${JSON.stringify(snapshot.sourceHash)};`,
    "",
  ].join("\n");
}

async function assertExactFile(target, expected, label) {
  const actual = await readFile(target);
  if (!actual.equals(expected))
    throw new Error(
      `${label} is out of date. Run pnpm review-policy:sync before committing.`,
    );
}

const checkOnly = process.argv.includes("--check");
const explicitSource =
  optionValue("--source") ??
  (process.env.REVIEW_LEADERSHIP_SKILL_DIR
    ? path.resolve(process.env.REVIEW_LEADERSHIP_SKILL_DIR)
    : undefined);
const sourceRoot =
  explicitSource ??
  path.join(os.homedir(), "skills", "review-leadership-situations");

if (checkOnly) {
  const committed = await loadSnapshot(snapshotRoot);
  await assertExactFile(
    path.join(snapshotRoot, "manifest.json"),
    Buffer.from(`${JSON.stringify(manifestFor(committed), null, 2)}\n`),
    "The committed review-policy manifest",
  );
  await assertExactFile(
    versionPath,
    Buffer.from(versionModule(committed)),
    "The committed review-policy version module",
  );

  if (await exists(sourceRoot)) {
    const source = await loadSnapshot(sourceRoot);
    if (source.sourceHash !== committed.sourceHash)
      throw new Error(
        `The committed review policy differs from ${sourceRoot}. Run pnpm review-policy:sync.`,
      );
  } else if (explicitSource) {
    throw new Error(`Review policy source does not exist: ${sourceRoot}`);
  }

  console.log(`Review policy ${committed.version} is valid and current.`);
} else {
  if (!(await exists(sourceRoot)))
    throw new Error(`Review policy source does not exist: ${sourceRoot}`);
  const source = await loadSnapshot(sourceRoot);
  for (const file of source.files) {
    const target = path.join(snapshotRoot, file.path);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, file.body);
  }
  await writeFile(
    path.join(snapshotRoot, "manifest.json"),
    `${JSON.stringify(manifestFor(source), null, 2)}\n`,
  );
  await mkdir(path.dirname(versionPath), { recursive: true });
  await writeFile(versionPath, versionModule(source));
  console.log(`Synced review policy ${source.version} from ${sourceRoot}.`);
}
